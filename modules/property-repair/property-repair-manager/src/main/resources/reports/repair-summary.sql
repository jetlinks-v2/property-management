select
  /* export-order-ids */
  business_project_id as "projectId",
  max(business_project_name) as "projectName",
  count(*) as "total",
  sum(case when status = 0 then 1 else 0 end) as "noDistributed",
  sum(case when status = 6 then 1 else 0 end) as "waitAccept",
  sum(case when status = 7 then 1 else 0 end) as "waitFollow",
  sum(case when status = 1 then 1 else 0 end) as "handling",
  sum(case when status = 8 then 1 else 0 end) as "waitCallback",
  sum(case when status = 9 then 1 else 0 end) as "waitAudit",
  sum(case when status = 5 then 1 else 0 end) as "archived",
  sum(case when status = 2 then 1 else 0 end) as "finished",
  sum(case when status = 4 then 1 else 0 end) as "close",
  sum(case when status = 3 then 1 else 0 end) as "abandoned",
  sum(case when accept_time is not null then 1 else 0 end) as "accepted",
  sum(case when status <> 3 and finish_time is not null then 1 else 0 end) as "completed",
  coalesce(avg(case when finish_time is not null then trunc((finish_time - create_time) / 60000.0) end),0) as "averageProcessingMinutes",
  sum(case when accept_time is not null and accept_time - coalesce((select max(p.create_time) from sp_repair_process p where p.order_id = sp_repair_order.id and p.action in ('dispatch','transfer','autoDispatch') and p.create_time <= sp_repair_order.accept_time), create_time) < 960000 then 1 else 0 end) as "timelyAccepted",
  sum(case when finish_time is not null and finish_deadline is not null then 1 else 0 end) as "withDeadline",
  sum(case when finish_time is not null and finish_deadline is not null and finish_time <= finish_deadline then 1 else 0 end) as "timelyCompleted",
  sum(case when owner_evaluated = true then 1 else 0 end) as "ownerEvaluated",
  sum(case when owner_evaluated = true and owner_satisfaction >= 4 and owner_satisfaction <= 5 then 1 else 0 end) as "ownerPositive",
  sum(case when paid = true then 1 else 0 end) as "paidCount",
  coalesce(sum(material_amount),0) as "materialAmount",
  coalesce(sum(artificial_amount),0) as "artificialAmount",
  coalesce(sum(total_amount),0) as "totalAmount",
  coalesce(sum(person_amount),0) as "personAmount",
  coalesce(sum(provider_amount),0) as "providerAmount",
  coalesce(sum(property_amount),0) as "propertyAmount",
  sum(case when finish_deadline >= ? and finish_deadline < ? then 1 else 0 end) as "range1",
  sum(case when finish_deadline >= ? and finish_deadline < ? then 1 else 0 end) as "range2",
  sum(case when finish_deadline >= ? and finish_deadline < ? then 1 else 0 end) as "range3",
  sum(case when finish_deadline >= ? and finish_deadline < ? then 1 else 0 end) as "range4",
  sum(case when finish_deadline < ? then 1 else 0 end) as "range5",
  sum(case when accept_time - create_time < 1860000 then 1 else 0 end) as "follow1",
  sum(case when accept_time - create_time >= 1860000 and accept_time - create_time < 3660000 then 1 else 0 end) as "follow2",
  sum(case when accept_time - create_time >= 3660000 and accept_time - create_time < 7260000 then 1 else 0 end) as "follow3",
  sum(case when accept_time - create_time >= 43260000 then 1 else 0 end) as "follow4",
  sum(case when paid = true and staff_evaluated = true then 1 else 0 end) + sum(case when paid = true and owner_evaluated = true then 1 else 0 end) as "paidReviews",
  sum(case when paid = true and staff_evaluated = true and staff_satisfaction >= 3 then 1 else 0 end) + sum(case when paid = true and owner_evaluated = true and owner_satisfaction >= 3 then 1 else 0 end) as "paidPositive"
from sp_repair_order
group by business_project_id
order by "projectName", "projectId"
